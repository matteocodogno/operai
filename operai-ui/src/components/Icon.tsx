export type IconName = keyof typeof PATHS

export const ICON_NAMES = Object.keys(PATHS) as IconName[]

export type IconProps = {
  name: IconName
  /** Pixel size. Defaults to 1em: the icon follows the text size. */
  size?: number | string
  /**
   * Accessible name, for an icon that carries meaning on its own. Omit it (the
   * usual case) when the icon sits next to text that says the same thing, or
   * inside a control that has its own `aria-label`: the icon is then hidden.
   */
  label?: string
  className?: string
}

/** Icon — one shape from the suite's set, drawn in the current text colour. */
export function Icon({ name, size = '1em', label, className }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cx('icon', className)}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  )
}
